def cell_pct(s):
    m = re.match(r"([\d.]+)% \((\d+)/(\d+)\)", s)
    return "%s%% (%s/%s)" % (vn(m.group(1)), m.group(2), m.group(3)) if m else s

def result_of(tbs, test):
    """runs / verdict text for a test on a list of testbenches"""
    rr = [r for tb in tbs for r in by.get((tb, test), [])]
    if not rr:
        return ("–", "–", "–")
    cfgs = []
    for r in rr:
        if r["Cfg"] not in cfgs:
            cfgs.append(r["Cfg"])
    p = sum(1 for r in rr if r["Result"] == "PASS")
    x = [r for r in rr if r["Result"] == "XFAIL"]
    if x:
        res = "XFAIL (%s)" % x[0]["Issue"]
    else:
        res = "%d/%d PASS" % (p, len(rr))
    return (", ".join(cfgs), str(len(rr)), res)

