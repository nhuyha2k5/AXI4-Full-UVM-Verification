def PIC(path, alt):
    """Inline picture, 16 cm wide (shrunk if it would be taller than 21 cm)."""
    data = open(path, "rb").read()
    w, h = struct.unpack(">II", data[16:24])
    cx = 5760000
    cy = int(cx * h / float(w))
    if cy > 7560000:
        cx, cy = int(cx * 7560000 / float(cy)), 7560000
    n = len(images) + 1
    rid = "rIdImg%d" % n
    images.append((rid, "image%d.png" % n, data))
    body.append(
        '<w:p><w:pPr><w:pStyle w:val="Figure"/></w:pPr><w:r><w:drawing>'
        '<wp:inline distT="0" distB="0" distL="0" distR="0"><wp:extent cx="%d" cy="%d"/><wp:docPr id="%d" name="Hình %d" descr="%s"/>'
        '<wp:cNvGraphicFramePr><a:graphicFrameLocks noChangeAspect="1"/></wp:cNvGraphicFramePr>'
        '<a:graphic><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:pic>'
        '<pic:nvPicPr><pic:cNvPr id="%d" name="image%d.png"/><pic:cNvPicPr/></pic:nvPicPr>'
        '<pic:blipFill><a:blip r:embed="%s"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>'
        '<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="%d" cy="%d"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr>'
        '</pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r></w:p>'
        % (cx, cy, n, n, escape(alt, {'"': "&quot;"}), n, n, rid, cx, cy))

def FIG(caption, what, howto=None):
    """A figure.  If docs/images/fig_<section>_<n>.png exists it is embedded; otherwise a highlighted
    placeholder (with a Word comment) tells the author what to insert and, with `howto`, how to make it."""
    fig_no[cur_sec[0]] += 1
    label = "Hình %d.%d" % (cur_sec[0], fig_no[cur_sec[0]])
    png = os.path.join(IMG_DIR, "fig_%d_%d.png" % (cur_sec[0], fig_no[cur_sec[0]]))
    if os.path.exists(png):
        PIC(png, "%s. %s" % (label, caption))
    else:
        cid = len(comments)
        comments.append("Cần thêm ảnh cho %s: %s" % (label, what))
        head = runs("[CHỖ NÀY CẦN THÊM ẢNH] ", bold=True, hl="yellow") + runs(what, hl="yellow")
        body.append(
            '<w:p><w:pPr><w:pStyle w:val="FigureNote"/></w:pPr>'
            '<w:commentRangeStart w:id="%d"/>%s<w:commentRangeEnd w:id="%d"/>'
            '<w:r>%s<w:commentReference w:id="%d"/></w:r></w:p>' % (cid, head, cid, rpr(), cid))
        for ln in (howto or []):
            body.append('<w:p><w:pPr><w:pStyle w:val="FigureNote"/></w:pPr>%s</w:p>' % runs(ln, size=21, hl="yellow"))
    para("%s. %s" % (label, caption), style="Caption")

