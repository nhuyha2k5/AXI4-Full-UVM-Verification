def TABLE(caption, header, data, widths):
    tab_no[cur_sec[0]] += 1
    para("Bảng %d.%d. %s" % (cur_sec[0], tab_no[cur_sec[0]], caption), style="TableCaption")
    total = 9071
    ws = [int(total * w / float(sum(widths))) for w in widths]
    ws[-1] += total - sum(ws)
    x = ['<w:tbl><w:tblPr><w:tblW w:w="%d" w:type="dxa"/><w:tblLayout w:type="fixed"/><w:tblBorders>' % total]
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        x.append('<w:%s w:val="single" w:sz="4" w:space="0" w:color="000000"/>' % side)
    x.append('</w:tblBorders><w:tblCellMar><w:left w:w="70" w:type="dxa"/><w:right w:w="70" w:type="dxa"/></w:tblCellMar></w:tblPr><w:tblGrid>')
    x += ['<w:gridCol w:w="%d"/>' % w for w in ws]
    x.append("</w:tblGrid>")

    def row(cells, head):
        s = "<w:tr>" + ("<w:trPr><w:tblHeader/></w:trPr>" if head else "<w:trPr><w:cantSplit/></w:trPr>")
        for w, c in zip(ws, cells):
            s += '<w:tc><w:tcPr><w:tcW w:w="%d" w:type="dxa"/>%s</w:tcPr>' % (
                w, '<w:shd w:val="clear" w:color="auto" w:fill="D9D9D9"/>' if head else "")
            for k, line in enumerate(str(c).split("\n")):
                s += '<w:p><w:pPr><w:pStyle w:val="TableText"/></w:pPr>%s</w:p>' % runs(line, bold=head, size=24)
            s += "</w:tc>"
        return s + "</w:tr>"

    x.append(row(header, True))
    x += [row(r, False) for r in data]
    x.append("</w:tbl>")
    body.append("".join(x))
    para("", style="AfterTable")

