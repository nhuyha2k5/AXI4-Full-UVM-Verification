<#
.SYNOPSIS
  Turn reports/regression_results.csv (written by regress.ps1) into reports/regression_summary.md.
.DESCRIPTION
  One row per test and build configuration: number of seeds, results, and the number of
  scoreboard comparisons ("checks") of the runs.  Nothing is typed by hand.
#>
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'dv_lib.ps1')
Push-Location $DvRoot
try {
    $allRows = Import-Csv reports/regression_results.csv
    $rows = @($allRows | Where-Object { $_.Result -notlike 'ORIG-*' })       # the regression proper
    $origRows = @($allRows | Where-Object { $_.Result -like 'ORIG-*' })      # reference runs on the original RTL
    $md = [System.Collections.Generic.List[string]]::new()
    $md.Add('# Regression summary')
    $md.Add('')
    $md.Add("Generated by ``scripts/regression_summary.ps1`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm') from ``reports/regression_results.csv``.")
    $md.Add('')
    $md.Add('A run is PASS only if its log has `TEST_RESULT: PASSED`, `UVM_ERROR : 0`, `UVM_FATAL : 0`, no simulator error,')
    $md.Add('and at least the minimum number of scoreboard comparisons of the test. XFAIL = test that demonstrates a known')
    $md.Add('design issue and is expected to fail (docs/KNOWN_ISSUES.md); XPASS (such a test passing) counts as a failure.')
    $md.Add('')
    $n = @{}
    foreach ($k in 'PASS', 'FAIL', 'XFAIL', 'XPASS') { $n[$k] = @($rows | Where-Object Result -eq $k).Count }
    $md.Add("**Total: $($rows.Count) runs - $($n.PASS) PASS, $($n.FAIL) FAIL, $($n.XFAIL) XFAIL, $($n.XPASS) XPASS.**")
    $md.Add('')
    $md.Add('| Testbench | Runs | PASS | FAIL | XFAIL | XPASS | Random-stimulus runs* |')
    $md.Add('|---|---|---|---|---|---|---|')
    foreach ($g in ($rows | Group-Object Tb)) {
        $c = @{}
        foreach ($k in 'PASS', 'FAIL', 'XFAIL', 'XPASS') { $c[$k] = @($g.Group | Where-Object Result -eq $k).Count }
        $multi = @($g.Group | Group-Object Test, Cfg | Where-Object Count -gt 1 | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum
        $md.Add("| $($g.Name) | $($g.Count) | $($c.PASS) | $($c.FAIL) | $($c.XFAIL) | $($c.XPASS) | $([int]$multi) |")
    }
    $md.Add('')
    $md.Add('\* runs of tests that are run with more than one seed.')
    $md.Add('')
    if ($origRows.Count -gt 0) {
        $md.Add('## Reference runs on the original RTL')
        $md.Add('')
        $md.Add('Every main test is repeated, with the same seeds, on RTL without the fix macros (crossbar) or on the unmodified files of the')
        $md.Add('original library (`upstream_ref/`). The outcome is informative (ORIG-PASS / ORIG-FAIL) and never counts as a regression failure.')
        $md.Add('')
        $md.Add('| Build | Runs | ORIG-PASS | ORIG-FAIL |')
        $md.Add('|---|---|---|---|')
        foreach ($g in ($origRows | Group-Object Tb)) {
            $p = @($g.Group | Where-Object Result -eq 'ORIG-PASS').Count
            $md.Add("| $($g.Name) | $($g.Count) | $p | $($g.Count - $p) |")
        }
        $md.Add('')
        $md.Add('Tests with at least one ORIG-FAIL: see the per-test table below.')
        $md.Add('')
    }
    $md.Add('## Per test')
    $md.Add('')
    $md.Add('| Testbench | Test | Build cfg | Seeds | Result | Checks per run (min - max) | Known issue |')
    $md.Add('|---|---|---|---|---|---|---|')
    foreach ($g in ($allRows | Group-Object Tb, Test, Cfg)) {
        $r0 = $g.Group[0]
        $res = ($g.Group | Group-Object Result | ForEach-Object { "$($_.Count) $($_.Name)" }) -join ', '
        $chk = $g.Group | ForEach-Object { [int]$_.Checks } | Measure-Object -Minimum -Maximum
        $range = if ($chk.Minimum -eq $chk.Maximum) { "$($chk.Minimum)" } else { "$($chk.Minimum) - $($chk.Maximum)" }
        $md.Add("| $($r0.Tb) | $($r0.Test) | $($r0.Cfg) | $($g.Count) | $res | $range | $($r0.Issue) |")
    }
    Set-Content -Path reports/regression_summary.md -Value $md
    Write-Host "wrote reports/regression_summary.md ($($rows.Count) runs)"
}
finally { Pop-Location }
